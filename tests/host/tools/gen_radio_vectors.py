"""Generate reference vectors for tests/host/tests/radio_security.cpp from Python's `cryptography` (an independent,
widely used implementation) and hashlib. Writes the C header given on the command line."""
import hashlib, struct, sys, zlib
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305

def c_bytes(b):
    return '{' + ','.join('0x%02x' % x for x in b) + '}' if b else '{0}'

out = []
out.append('// Generated by gen_vectors.py from Python cryptography %s + hashlib. Do not edit.' % __import__('cryptography').__version__)

# RFC 8439 2.8.2 AEAD vector
key = bytes(range(0x80, 0xa0))
nonce = bytes([0x07, 0, 0, 0]) + bytes(range(0x40, 0x48))
aad = bytes([0x50, 0x51, 0x52, 0x53, 0xc0, 0xc1, 0xc2, 0xc3, 0xc4, 0xc5, 0xc6, 0xc7])
pt = b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it."
ct = ChaCha20Poly1305(key).encrypt(nonce, pt, aad)
assert ct[-16:].hex() == '1ae10b594f09e26a7e902ecbd0600691'   # the tag printed in RFC 8439
out.append('const uint8_t RFC_KEY[32] = %s;' % c_bytes(key))
out.append('const uint8_t RFC_NONCE[12] = %s;' % c_bytes(nonce))
out.append('const uint8_t RFC_AAD[12] = %s;' % c_bytes(aad))
out.append('const char RFC_PT[] = "%s";' % pt.decode().replace('"', '\\"'))
out.append('const uint8_t RFC_CT_TAG[%d] = %s;' % (len(ct), c_bytes(ct)))

# SHA-256
for name, msg in (('SHA_EMPTY', b''), ('SHA_ABC', b'abc'), ('SHA_LONG', bytes((i * 7 + 3) & 0xff for i in range(200)))):
    out.append('const uint8_t %s[32] = %s;' % (name, c_bytes(hashlib.sha256(msg).digest())))

# Key from a phrase, and its 4-character code
prefix = b'waterski-ramp/bind/v1:'
for name, phrase in (('UNBOUND', b''), ('PHRASE', b'correct horse battery staple')):
    k = hashlib.sha256(prefix + phrase).digest()
    code = hashlib.sha256(k).digest()[:2].hex().upper()
    out.append('const uint8_t KEY_%s[32] = %s;' % (name, c_bytes(k)))
    out.append('const char CODE_%s[] = "%s";' % (name, code))

# Whole packets as rsSeal builds them, with the unbound key, every payload length 0..40, with and without an echo
k = hashlib.sha256(prefix).digest()
out.append('struct SealVec { uint8_t sender; uint32_t fcnt; bool hasEcho; uint32_t echo; uint8_t len; uint8_t pkt[5 + 40 + 4]; };')
out.append('const SealVec SEAL_VECS[] = {')
for n in range(0, 41):
    for has_echo in (False, True):
        sender = 0xA1 if not has_echo else 0xB3
        fcnt = 0x01020304 * (n + 1) & 0xffffffff
        echo = 0xdeadbeef ^ n
        plain = bytes((i * 31 + n) & 0xff for i in range(n))
        nonce = bytes([sender]) + struct.pack('<I', fcnt) + bytes(7)
        header = bytes([sender]) + struct.pack('<I', fcnt)
        a = header + (struct.pack('<I', echo) if has_echo else b'')
        ct = ChaCha20Poly1305(k).encrypt(nonce, plain, a)
        pkt = header + ct[:-16] + ct[-16:][:4]
        out.append('  {0x%02x, 0x%08xu, %s, 0x%08xu, %d, %s},' % (sender, fcnt, 'true' if has_echo else 'false', echo, n, c_bytes(pkt)))
out.append('};')

# The web flasher's bind block (magic, length, phrase, CRC-32 of length + phrase)
phrase = b'correct horse battery staple'
body = bytes([len(phrase)]) + phrase
block = b'WSRBIND1' + body + struct.pack('<I', zlib.crc32(body))
out.append('const uint8_t BIND_BLOCK[%d] = %s;' % (len(block), c_bytes(block)))

open(sys.argv[1], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('wrote', sys.argv[1])
